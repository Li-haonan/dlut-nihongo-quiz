function updateFile(filePath, type) {
  const content = fs.readFileSync(filePath, 'utf-8')
  const lines = content.split('\n')
  const newLines = []
  let currentNum = null
  let addedCount = 0

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    newLines.push(line)

    // Detect question number
    const m = line.match(/^\*\*(\d+)\./)
    if (m) {
      currentNum = parseInt(m[1])
    }

    // Detect answer line and add explanation after it
    if (line.startsWith('**答案**') && currentNum !== null) {
      const expKey = String(currentNum)
      if (explanations[type] && explanations[type][expKey]) {
        // Check if next line already has explanation
        const nextLine = lines[i + 1]
        if (!nextLine || !nextLine.startsWith('**解析**')) {
          newLines.push('')
          newLines.push(`**解析**：${explanations[type][expKey]}`)
          addedCount++
        }
      }
    }
  }

  fs.writeFileSync(filePath, newLines.join('\n'), 'utf-8')
  console.log(`Updated ${filePath}: added ${addedCount} explanations`)
}

